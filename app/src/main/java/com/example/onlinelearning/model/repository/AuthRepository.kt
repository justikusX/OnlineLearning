package com.example.onlinelearning.model.repository

import android.annotation.SuppressLint
import android.app.Activity
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import com.google.android.libraries.identity.googleid.GetSignInWithGoogleOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.google.firebase.FirebaseException
import com.google.firebase.auth.AuthCredential
import com.google.firebase.auth.FirebaseAuth
import com.google.firebase.auth.FirebaseUser
import com.google.firebase.auth.GoogleAuthProvider
import com.google.firebase.auth.PhoneAuthCredential
import com.google.firebase.auth.PhoneAuthOptions
import com.google.firebase.auth.PhoneAuthProvider
import com.google.firebase.auth.userProfileChangeRequest
import kotlinx.coroutines.channels.awaitClose
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.callbackFlow
import kotlinx.coroutines.flow.flowOf
import kotlinx.coroutines.suspendCancellableCoroutine
import kotlinx.coroutines.tasks.await
import java.util.concurrent.TimeUnit
import kotlin.coroutines.resume
import kotlin.coroutines.resumeWithException

sealed interface PhoneVerification {
    data class CodeSent(
        val verificationId: String,
        val resendToken: PhoneAuthProvider.ForceResendingToken,
    ) : PhoneVerification

    data class AutoVerified(val credential: PhoneAuthCredential) : PhoneVerification
}

class FirebaseNotConfiguredException : IllegalStateException(
    "Firebase не настроен: добавьте app/google-services.json и пересоберите проект"
)

/** Email/password auth via Firebase Auth. [auth] is null when google-services.json is missing. */
class AuthRepository(private val auth: FirebaseAuth?) {

    val isConfigured: Boolean get() = auth != null

    val currentUser: FirebaseUser? get() = auth?.currentUser

    val userFlow: Flow<FirebaseUser?> = auth?.let { firebaseAuth ->
        callbackFlow {
            val listener = FirebaseAuth.AuthStateListener { trySend(it.currentUser) }
            firebaseAuth.addAuthStateListener(listener)
            awaitClose { firebaseAuth.removeAuthStateListener(listener) }
        }
    } ?: flowOf(null)

    suspend fun signIn(email: String, password: String): FirebaseUser {
        val result = requireAuth().signInWithEmailAndPassword(email, password).await()
        return checkNotNull(result.user)
    }

    suspend fun signUp(name: String, email: String, password: String): FirebaseUser {
        val result = requireAuth().createUserWithEmailAndPassword(email, password).await()
        val user = checkNotNull(result.user)
        user.updateProfile(userProfileChangeRequest { displayName = name }).await()
        return user
    }

    /** "Sign in with Google" via Credential Manager, then Firebase Auth. Needs the Google provider enabled. */
    @SuppressLint("DiscouragedApi")
    suspend fun signInWithGoogle(activity: Activity): FirebaseUser {
        requireAuth() // fail early with a clear message when Firebase is not configured
        // Generated by the google-services plugin from google-services.json (looked up by name so the
        // project still compiles without that file).
        val clientIdRes = activity.resources.getIdentifier("default_web_client_id", "string", activity.packageName)
        if (clientIdRes == 0) throw FirebaseNotConfiguredException()
        val request = GetCredentialRequest.Builder()
            .addCredentialOption(GetSignInWithGoogleOption.Builder(activity.getString(clientIdRes)).build())
            .build()
        val credential = CredentialManager.create(activity).getCredential(activity, request).credential
        check(credential is CustomCredential && credential.type == GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
            "Не удалось получить аккаунт Google"
        }
        val idToken = GoogleIdTokenCredential.createFrom(credential.data).idToken
        return signInWithCredential(GoogleAuthProvider.getCredential(idToken, null))
    }

    /**
     * Sends an SMS code to [phone] (international format, e.g. +79991234567).
     * Returns either the id needed to check the code or a credential when Android verified the number itself.
     */
    suspend fun sendPhoneCode(
        activity: Activity,
        phone: String,
        resendToken: PhoneAuthProvider.ForceResendingToken? = null,
    ): PhoneVerification = suspendCancellableCoroutine { cont ->
        val callbacks = object : PhoneAuthProvider.OnVerificationStateChangedCallbacks() {
            override fun onVerificationCompleted(credential: PhoneAuthCredential) {
                if (cont.isActive) cont.resume(PhoneVerification.AutoVerified(credential))
            }

            override fun onVerificationFailed(e: FirebaseException) {
                if (cont.isActive) cont.resumeWithException(e)
            }

            override fun onCodeSent(verificationId: String, token: PhoneAuthProvider.ForceResendingToken) {
                if (cont.isActive) cont.resume(PhoneVerification.CodeSent(verificationId, token))
            }
        }
        val options = PhoneAuthOptions.newBuilder(requireAuth())
            .setPhoneNumber(phone)
            .setTimeout(60L, TimeUnit.SECONDS)
            .setActivity(activity)
            .setCallbacks(callbacks)
        resendToken?.let { options.setForceResendingToken(it) }
        PhoneAuthProvider.verifyPhoneNumber(options.build())
    }

    suspend fun signInWithPhoneCode(verificationId: String, code: String): FirebaseUser =
        signInWithCredential(PhoneAuthProvider.getCredential(verificationId, code))

    suspend fun signInWithCredential(credential: AuthCredential): FirebaseUser {
        val result = requireAuth().signInWithCredential(credential).await()
        return checkNotNull(result.user)
    }

    suspend fun updateDisplayName(name: String) {
        auth?.currentUser?.updateProfile(userProfileChangeRequest { displayName = name })?.await()
    }

    suspend fun sendPasswordReset(email: String) {
        requireAuth().sendPasswordResetEmail(email).await()
    }

    fun signOut() {
        auth?.signOut()
    }

    private fun requireAuth(): FirebaseAuth = auth ?: throw FirebaseNotConfiguredException()
}
